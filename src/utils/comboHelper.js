/**
 * Returns an array of combo items for a given product object, or null if it's a single product.
 */
export const getComboItems = (product) => {
  if (!product) return null;

  // 1. Direct comboItems array from product
  if (Array.isArray(product.comboItems) && product.comboItems.length >= 2) {
    return product.comboItems;
  }

  // 2. Direct comboImages array
  if (Array.isArray(product.comboImages) && product.comboImages.length >= 2) {
    const isDouble = String(product.name || '').includes('2 ANTOX') || String(product.id || '').includes('2d');
    return [
      {
        name: isDouble ? '2x Product 1' : '1x Product 1',
        count: isDouble ? 2 : 1,
        image: product.comboImages[0],
        fallback: product.fallbackImage || product.comboImages[0]
      },
      {
        name: '1x Product 2',
        count: 1,
        image: product.comboImages[1],
        fallback: product.comboImages[1]
      }
    ];
  }

  // 3. Match from catalog by ID
  const rawId = String(product.id || '').trim();
  if (COMBO_CATALOG[rawId]) {
    return COMBO_CATALOG[rawId].items;
  }

  // 4. Match by name or alias patterns
  const nameLower = (product.nameEn || product.name || product.nameMr || '').toLowerCase();
  const aliasLower = (product.alias || '').toLowerCase();

  if (nameLower.includes('2 antox-d') || aliasLower.includes('2-antox-d') || nameLower.includes('२ antox-d')) {
    return COMBO_CATALOG.prod_antox_2d_1t_combo.items;
  }
  if ((nameLower.includes('antox-d') && nameLower.includes('antox-t')) || aliasLower.includes('antox-d-t') || (nameLower.includes('antox-d') && nameLower.includes('आणि'))) {
    return COMBO_CATALOG.prod_antox_d_combo.items;
  }
  if ((nameLower.includes('spray') && nameLower.includes('antox-t')) || aliasLower.includes('spray-nico-t')) {
    return COMBO_CATALOG.prod_spray_nico_combo.items;
  }
  if ((nameLower.includes('powder') && nameLower.includes('oil')) || aliasLower.includes('antox-pn-kit') || (nameLower.includes('पावडर') && nameLower.includes('ऑईल'))) {
    return COMBO_CATALOG.prod_antox_pn_combo.items;
  }
  if ((nameLower.includes('hlk') && nameLower.includes('antox-t')) || aliasLower.includes('antox-hlk-t')) {
    return COMBO_CATALOG.prod_antox_hlk_combo.items;
  }
  if ((nameLower.includes('acid') && nameLower.includes('antox-t')) || aliasLower.includes('antox-b-acid-t')) {
    return COMBO_CATALOG.prod_antox_b_acid_combo.items;
  }
  if ((nameLower.includes('amrut') && nameLower.includes('antox-t')) || aliasLower.includes('antox-amrut-51-t') || nameLower.includes('अमृत')) {
    return COMBO_CATALOG.prod_antox_amrut_51_combo.items;
  }
  if ((nameLower.includes('antox- x') || nameLower.includes('antox-x') || nameLower.includes('antox - x')) && nameLower.includes('antox-t')) {
    return COMBO_CATALOG.prod_antox_x_combo.items;
  }

  return null;
};
